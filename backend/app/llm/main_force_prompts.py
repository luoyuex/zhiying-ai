def build_analyst_prompt(
    kind: str,
    summary: str,
    table: str,
    strategy: str = "main_force",
) -> str:
    tasks = STRATEGY_ANALYST_TASKS.get(strategy, ANALYST_TASKS)
    task = tasks[kind]
    return f"""【整体数据摘要】
{summary}

【候选股票详细数据】
{table}

【分析任务】
{task}
"""


